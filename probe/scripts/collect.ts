// Collects every run record under runs/ into data/verified/<client>.json:
// one canimcp Evidence record per (client, client version, scenario,
// protocol revision, config), keyed by the capability id, in the overlay
// shape schema/verified-evidence.schema.json describes.
//
//   node dist/scripts/collect.js [--runs runs] [--out ../data/verified]
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { arg } from '../lib/capture.js';

const here = dirname(fileURLToPath(import.meta.url));
const probeRoot = resolve(here, '../..');
const runsRoot = resolve(probeRoot, arg('runs', 'runs'));
const outDir = resolve(probeRoot, arg('out', '../data/verified'));

interface Record_ {
  client: string;
  capability: string;
  scenario: string;
  evidence: Record<string, unknown> & { clientVersion: string; config: string };
  run: Record<string, unknown>;
}

const clientsRegistry = JSON.parse(readFileSync(resolve(probeRoot, 'registry/clients.json'), 'utf8')) as {
  clients: Record<string, { registryId?: string; title: string }>;
};

const byClient = new Map<string, Record_[]>();
for (const dir of readdirSync(runsRoot, { withFileTypes: true })) {
  if (!dir.isDirectory() || dir.name.startsWith('_')) continue;
  const indexPath = join(runsRoot, dir.name, 'index.json');
  if (!existsSync(indexPath)) continue;
  const records = JSON.parse(readFileSync(indexPath, 'utf8')) as Record_[];
  for (const r of records) {
    const list = byClient.get(r.client) ?? [];
    list.push(r);
    byClient.set(r.client, list);
  }
}

mkdirSync(outDir, { recursive: true });
for (const [client, records] of byClient) {
  const meta = clientsRegistry.clients[client];
  const entry: Record<string, unknown> = {
    $comment: `Generated by probe/scripts/collect.ts from probe/runs/${client}@*/index.json. Do not edit; rerun the probe.`,
    client,
    registryId: meta?.registryId ?? null,
    title: meta?.title ?? client,
    versions: [...new Set(records.map((r) => r.evidence.clientVersion))],
  };
  const capabilities: Record<string, { evidence: unknown[] }> = {};
  for (const r of records.sort((a, b) => a.scenario.localeCompare(b.scenario) || a.evidence.config.localeCompare(b.evidence.config))) {
    const cap = (capabilities[r.capability] ??= { evidence: [] });
    cap.evidence.push({ ...r.evidence, run: r.run });
  }
  entry.capabilities = capabilities;
  const outPath = join(outDir, `${client}.json`);
  writeFileSync(outPath, JSON.stringify(entry, null, 2) + '\n');
  console.log(`${client}: ${records.length} records -> ${outPath}`);
}
