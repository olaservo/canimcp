// Collects every run record under runs/ into data/verified/<client>.json:
// one canimcp Evidence record per (client, client version, scenario,
// protocol revision, config), keyed by the capability id, in the overlay
// shape schema/verified-evidence.schema.json describes. The conformance
// overlays in conformance/ingest-preview/ are merged in by their registryId,
// which is the probe adapter id.
//
//   node dist/scripts/collect.js [--runs runs] [--out ../data/verified] [--conformance conformance/ingest-preview]
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { arg } from '../lib/capture.js';
import type { HostAdapter } from '../lib/hosts.js';

const here = dirname(fileURLToPath(import.meta.url));
const probeRoot = resolve(here, '../..');
const runsRoot = resolve(probeRoot, arg('runs', 'runs'));
const outDir = resolve(probeRoot, arg('out', '../data/verified'));
const conformanceDir = resolve(probeRoot, arg('conformance', 'conformance/ingest-preview'));

interface Record_ {
  client: string;
  capability: string;
  scenario: string;
  evidence: Record<string, unknown> & { clientVersion: string; config: string; configKind?: string };
  run: Record<string, unknown>;
}

const clientsRegistry = JSON.parse(readFileSync(resolve(probeRoot, 'registry/clients.json'), 'utf8')) as {
  clients: Record<string, { registryId?: string; title: string }>;
};
const mapping = JSON.parse(readFileSync(resolve(probeRoot, 'conformance/mapping.json'), 'utf8')) as { proposed: Record<string, unknown> };

const byClient = new Map<string, Record_[]>();
for (const dir of readdirSync(runsRoot, { withFileTypes: true })) {
  if (!dir.isDirectory() || dir.name.startsWith('_')) continue;
  const indexPath = join(runsRoot, dir.name, 'index.json');
  if (!existsSync(indexPath)) continue;
  const records = JSON.parse(readFileSync(indexPath, 'utf8')) as Record_[];
  for (const r of records) {
    const list = byClient.get(r.client) ?? [];
    list.push(r);
    byClient.set(r.client, list);
  }
}

// The adapter declares each config's kind; records written before the field existed get it here.
const kinds = new Map<string, Map<string, string>>();
for (const client of byClient.keys()) {
  const { default: adapter } = (await import(pathToFileURL(resolve(here, '../hosts', client, 'adapter.js')).href)) as { default: HostAdapter };
  kinds.set(client, new Map(adapter.configs.map((c) => [c.name, c.kind])));
}

// Conformance evidence per adapter id. Proposed capability ids are not in the registry yet, so they stay in the preview.
const conformance = new Map<string, { versions: string[]; capabilities: Record<string, { evidence: unknown[] }> }[]>();
if (existsSync(conformanceDir)) {
  for (const f of readdirSync(conformanceDir).filter((n) => n.endsWith('.json')).sort()) {
    const o = JSON.parse(readFileSync(join(conformanceDir, f), 'utf8')) as { registryId: string; versions: string[]; capabilities: Record<string, { evidence: unknown[] }> };
    const list = conformance.get(o.registryId) ?? [];
    list.push(o);
    conformance.set(o.registryId, list);
  }
}

mkdirSync(outDir, { recursive: true });
for (const client of new Set([...byClient.keys(), ...conformance.keys()])) {
  const records = byClient.get(client) ?? [];
  const extra = conformance.get(client) ?? [];
  const meta = clientsRegistry.clients[client];
  const entry: Record<string, unknown> = {
    $comment: `Generated by probe/scripts/collect.ts from probe/runs/${client}@*/index.json and probe/conformance/ingest-preview/. Do not edit; rerun the probe.`,
    client,
    registryId: meta?.registryId ?? null,
    title: meta?.title ?? client,
    versions: [...new Set([...records.map((r) => r.evidence.clientVersion), ...extra.flatMap((o) => o.versions)])],
  };
  const capabilities: Record<string, { evidence: unknown[] }> = {};
  for (const r of records.sort((a, b) => a.scenario.localeCompare(b.scenario) || a.evidence.config.localeCompare(b.evidence.config))) {
    const configKind = kinds.get(client)?.get(r.evidence.config) ?? r.evidence.configKind;
    if (!configKind) throw new Error(`${client}: config ${r.evidence.config} is not declared by the adapter and the record has no configKind`);
    const cap = (capabilities[r.capability] ??= { evidence: [] });
    cap.evidence.push({ ...r.evidence, configKind, run: r.run });
  }
  let fromConformance = 0;
  for (const o of extra) {
    for (const [capId, cap] of Object.entries(o.capabilities)) {
      if (capId in mapping.proposed) continue;
      (capabilities[capId] ??= { evidence: [] }).evidence.push(...cap.evidence);
      fromConformance += cap.evidence.length;
    }
  }
  entry.capabilities = capabilities;
  const outPath = join(outDir, `${client}.json`);
  writeFileSync(outPath, JSON.stringify(entry, null, 2) + '\n');
  console.log(`${client}: ${records.length} probe records, ${fromConformance} conformance records -> ${outPath}`);
}
